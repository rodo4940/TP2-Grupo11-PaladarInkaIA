"""Pruebas de negocio y capturas reales de la interfaz negro/oro.
Todas las cifras proceden de FastAPI + PostgreSQL con datos de laboratorio."""
import json,os,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
folder=Path('e2e/evidencias')
manifest_file=folder/'e2e-results.json'
manifest=json.loads(manifest_file.read_text(encoding='utf-8'))
base=os.environ.get('E2E_FRONTEND_URL','http://127.0.0.1:5173')
password=os.environ['SEED_ADMIN_PASSWORD']

def shot(page,name,description):
    page.screenshot(path=str(folder/name),full_page=True,animations='disabled')
    manifest['screenshots'].append({'file':name,'step':description,'source':'Navegador Chromium real, datos ficticios'})
    print('EVIDENCIA',name,flush=True)

def nav(page,name,heading):
    page.locator('nav').get_by_role('button',name=name,exact=True).click()
    expect(page.get_by_role('heading',name=heading,exact=True).first).to_be_visible()

with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':900},locale='es-PE')
    page.set_default_timeout(18000)
    page.goto(base)
    page.locator('input[autocomplete="username"]').fill('admin')
    page.locator('input[autocomplete="current-password"]').fill(password)
    page.get_by_role('button',name='Ingresar al sistema').click()
    expect(page.get_by_role('heading',name='¡Bienvenido a Paladar Inka AI!')).to_be_visible()
    shot(page,'25_dashboard_despues_primer_cobro.png','Dashboard de operaciones cargado desde API')
    nav(page,'Clientes','Clientes')
    form=page.locator('form').filter(has=page.get_by_role('button',name='Guardar cliente')).first
    form.get_by_label('Nombre completo').fill('Cliente integral de pruebas QA')
    form.get_by_role('button',name='Guardar cliente').click()
    expect(page.get_by_role('alert')).to_contain_text('Cliente registrado')
    shot(page,'26_cliente_creado_en_interfaz.png','Cliente creado contra base PostgreSQL')
    nav(page,'Ventas (POS)','Ventas / Caja POS')
    add=page.locator('.pi-pos-card-body button')
    expect(add.first).to_be_visible()
    add.first.click()
    if add.count()>1: add.nth(1).click()
    page.get_by_label('Mesa o referencia').fill('Mesa QA-07')
    page.get_by_label('Notas del pedido').fill('Comanda automatizada de integración')
    shot(page,'27_pos_carrito_dos_pizzas.png','Carrito con productos del catálogo real')
    page.get_by_role('button',name='Enviar pedido a cocina sin cobrar').click()
    expect(page.locator('.pi-pos-locked')).to_be_visible()
    shot(page,'28_pedido_dos_pizzas_confirmado.png','Pedido registrado en backend; aún sin pagar')
    page.locator('.pi-pos-pay-methods button').filter(has_text='Yape').click()
    shot(page,'29_metodo_de_pago_yape.png','Selección de Yape en registro interno de cobros')
    page.get_by_role('button',name='Confirmar cobro del pedido').click()
    expect(page.get_by_role('dialog',name='Venta completada')).to_be_visible()
    shot(page,'30_yape_pago_confirmado.png','Registro interno de pago único confirmado')
    page.get_by_role('button',name='Nueva venta').click()
    nav(page,'Pedidos','Gestión de pedidos')
    row=page.locator('.pi-orders-table-wrap tbody tr').filter(has_text='Mesa QA-07').first
    expect(row).to_be_visible()
    row.click()
    expect(page.locator('.pi-order-detail')).to_contain_text('Mesa QA-07')
    shot(page,'31_detalle_trazabilidad_pedido.png','Pedido con productos, importe y estados')
    nav(page,'Cocina','Cocina – KDS')
    card=page.locator('.pi-kds-card').filter(has_text='Mesa QA-07')
    expect(card).to_be_visible()
    shot(page,'32_comanda_pendiente_cocina.png','Comanda registrada en tablero KDS real')
    card.get_by_role('button',name='Iniciar preparación').click()
    expect(page.locator('.pi-kds-lane-preparing .pi-kds-card').filter(has_text='Mesa QA-07')).to_be_visible()
    shot(page,'33_comanda_en_preparacion.png','Transición API a preparando')
    card=page.locator('.pi-kds-lane-preparing .pi-kds-card').filter(has_text='Mesa QA-07')
    card.get_by_role('button',name='Marcar listo').click()
    expect(page.locator('.pi-kds-lane-ready .pi-kds-card').filter(has_text='Mesa QA-07')).to_be_visible()
    shot(page,'34_comanda_lista.png','Pedido listo para entregar')
    card=page.locator('.pi-kds-lane-ready .pi-kds-card').filter(has_text='Mesa QA-07')
    card.get_by_role('button',name='Entregar').click()
    expect(page.locator('.pi-kds-lane-delivered .pi-kds-card').filter(has_text='Mesa QA-07')).to_be_visible()
    shot(page,'35_comanda_entregada.png','Pedido entregado, disponible en historial')
    nav(page,'Inventario','Inventario')
    line=page.locator('.pi-inventory-table-wrap tbody tr').filter(has_text='Harina').first
    expect(line).to_be_visible()
    line.click()
    form=page.locator('#pi-stock-form')
    form.get_by_label('Variación (+ entrada, − salida)').fill('500')
    form.get_by_label('Motivo').fill('Reposición registrada para prueba de integración')
    form.get_by_role('button',name='Guardar movimiento').click()
    expect(page.get_by_role('status')).to_contain_text('Movimiento de inventario registrado')
    shot(page,'36_kardex_reposicion_aprobada.png','Movimiento trazable de insumos')
    nav(page,'Reportes','Reportes y análisis')
    expect(page.get_by_text('Yape').first).to_be_visible()
    shot(page,'37_reporte_ventas_yape_efectivo.png','Reporte de métodos de pago registrados')
    nav(page,'IA y recomendaciones','Inteligencia operativa')
    shot(page,'38_analitica_ventas_confirmadas.png','Análisis explicable y laboratorio predictivo identificado')
    manifest['screenshot_count']=len(manifest['screenshots'])
    manifest_file.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    print('TOTAL CAPTURAS',len(manifest['screenshots']),flush=True)
    browser.close()
