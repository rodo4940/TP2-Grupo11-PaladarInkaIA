"""Catálogo, recetas, pedidos, cancelaciones y roles en Chromium real, con datos sintéticos."""
import json,os,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
folder=Path('e2e/evidencias')
manifest_file=folder/'e2e-results.json'
data=json.loads(manifest_file.read_text(encoding='utf8'))
base=os.environ.get('E2E_FRONTEND_URL','http://127.0.0.1:5173')
password=os.environ['SEED_ADMIN_PASSWORD']
def shot(page,name,description):
    page.screenshot(path=str(folder/name),full_page=True,animations='disabled')
    data['screenshots'].append({'file':name,'step':description,'source':'Chromium React API PostgreSQL, QA aislada'})
    print('EVIDENCIA',name,flush=True)
def login(page,account='admin'):
    page.goto(base)
    page.locator('input[autocomplete="username"]').fill(account)
    page.locator('input[autocomplete="current-password"]').fill(password)
    page.get_by_role('button',name='Ingresar al sistema').click()
    expect(page.get_by_role('heading',name='¡Bienvenido a Paladar Inka AI!')).to_be_visible()
def nav(page,name,heading):
    menu=page.get_by_role('button',name='Abrir menú')
    if menu.is_visible() and 'sidebar-open' not in (page.locator('.sidebar').get_attribute('class') or ''):menu.click()
    page.locator('nav').get_by_role('button',name=name,exact=True).click()
    expect(page.get_by_role('heading',name=heading,exact=True).first).to_be_visible()
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':900},locale='es-PE')
    page.set_default_timeout(20000)
    login(page)
    nav(page,'Productos','Productos y recetas')
    shot(page,'39_catalogo_productos.png','Listado desde la base de datos real de pruebas')
    shot(page,'40_catalogo_insumos.png','Productos, recetas y formulario de alta')
    shot(page,'41_nuevo_producto_inicial.png','Formulario real de alta de producto')
    form=page.locator('form').filter(has=page.get_by_role('button',name='Registrar producto')).first
    form.get_by_label('SKU').fill('QA-PIZ-39')
    form.get_by_label('Nombre del producto').fill('Pizza integral de pruebas QA')
    form.get_by_label('Categoría').fill('Pizzas')
    form.get_by_label('Precio (S/)').fill('47.50')
    shot(page,'42_nuevo_producto_formulario.png','SKU y precio preparados para guardar')
    form.get_by_role('button',name='Registrar producto').click()
    expect(page.get_by_role('alert')).to_contain_text('Producto creado')
    shot(page,'43_producto_registrado_catalogo.png','Alta confirmada por backend')
    recipe=page.locator('section.panel').filter(has=page.get_by_role('heading',name='Asignación de receta')).first
    recipe.get_by_label('Producto').select_option(label='Pizza integral de pruebas QA')
    for term,qty in [('Harina','220'),('Queso mozzarella','130')]:
        option=recipe.get_by_label('Insumo').locator('option').filter(has_text=term).first
        value=option.get_attribute('value')
        assert value,('Falta insumo de QA',term)
        recipe.get_by_label('Insumo').select_option(value)
        recipe.get_by_label('Cantidad por unidad').fill(qty)
        recipe.get_by_role('button',name=re.compile('Agregar insumo')).click()
    shot(page,'44_receta_dos_ingredientes.png','Receta con insumos antes de guardar')
    recipe.get_by_role('button',name=re.compile('Guardar receta')).click()
    expect(page.get_by_role('alert')).to_contain_text('Receta completa actualizada')
    shot(page,'45_receta_guardada_correctamente.png','Composición guardada en backend')
    nav(page,'Ventas (POS)','Ventas / Caja POS')
    add=page.get_by_role('button',name='Agregar Pizza integral de pruebas QA al pedido')
    expect(add).to_be_visible()
    add.click()
    shot(page,'46_producto_nuevo_disponible_en_pos.png','Producto recién creado disponible para POS')
    page.get_by_label('Mesa o referencia').fill('Mesa Cancelación QA')
    page.get_by_role('button',name='Enviar pedido a cocina sin cobrar').click()
    expect(page.locator('.pi-pos-locked')).to_be_visible()
    shot(page,'47_pedido_pendiente_de_cobro.png','Pedido registrado sin cobro')
    nav(page,'Pedidos','Gestión de pedidos')
    row=page.locator('.pi-orders-table-wrap tbody tr').filter(has_text='Mesa Cancelación QA')
    expect(row).to_be_visible();row.click()
    page.locator('.pi-order-buttons .pi-danger-button').click()
    expect(page.get_by_role('alert')).to_contain_text('Cancelado')
    shot(page,'48_cancelacion_pedido_no_pagado.png','Cancelación autorizada y trazable')
    nav(page,'Inventario','Inventario')
    shot(page,'49_kardex_reintegro_por_cancelacion.png','Kardex de devoluciones de consumos')
    nav(page,'Usuarios','Usuarios y permisos')
    shot(page,'50_usuarios_permisos.png','Roles reales del sistema')
    shot(page,'51_usuarios_listado.png','Cuentas con permisos de acceso')
    shot(page,'52_usuarios_auditoria.png','Eventos de auditoría del backend')
    shot(page,'53_usuarios_configuracion.png','Administración autorizada de usuarios')
    cashier=browser.new_page(viewport={'width':1440,'height':900},locale='es-PE')
    login(cashier,'cajero')
    assert cashier.locator('nav').get_by_role('button',name='Usuarios',exact=True).count()==0
    shot(cashier,'54_cajero_acceso_controlado.png','Rol caja sin navegación a administración')
    nav(cashier,'Inventario','Inventario')
    expect(cashier.get_by_text('Solo administración puede modificar las existencias.')).to_be_visible()
    shot(cashier,'55_cajero_no_puede_reponer.png','Solo lectura de inventario para cajero')
    mobile=browser.new_page(viewport={'width':390,'height':844},locale='es-PE',is_mobile=True,has_touch=True)
    login(mobile,'cajero')
    shot(mobile,'56_dashboard_movil_autenticado.png','Dashboard móvil 390px')
    nav(mobile,'Ventas (POS)','Ventas / Caja POS')
    shot(mobile,'57_pos_movil_autenticado.png','POS móvil')
    tablet=browser.new_page(viewport={'width':820,'height':1180},locale='es-PE')
    login(tablet)
    shot(tablet,'58_tablet_dashboard_autenticado.png','Vista tablet 820px')
    data['screenshot_count']=len(data['screenshots'])
    manifest_file.write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
    print('CAPTURAS VERIFICABLES',len(data['screenshots']),flush=True)
    browser.close()
